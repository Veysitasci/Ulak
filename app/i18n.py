class I18n:
    _instance = None
    
    def __new__(cls):
        if cls._instance is None:
            cls._instance = super(I18n, cls).__new__(cls)
            cls._instance.current_lang = "tr"
        return cls._instance

    def set_lang(self, lang):
        self.current_lang = lang if lang in LANG else "en"
        
    def get(self, key):
        return LANG.get(self.current_lang, LANG["en"]).get(key, key)

i18n_instance = I18n()

def _(key):
    return i18n_instance.get(key)
